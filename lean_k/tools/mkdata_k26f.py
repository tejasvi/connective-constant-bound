# mkdata_k26f.py PREFIX OUT JOBS: pack the k26f certificate (PREFIX.keys, .chosen, .v) into the K26F data files.
#   OUT/data/m%04d.bin: module m = records [m R, min(N, (m+1) R)), R = 2^20, as leaves of L = 64 records of 26 bytes
#   (208 bits, little endian): n (6 bits) | T (44) | c0 (30) | c1 (30) | c2 (30) | V (62); child 2^32-1 -> 2^30-1;
#   V = floor(v 2^60). The last leaf of the last module is padded with zero records (never read: indices >= N).
#   OUT/data/MANIFEST.tsv: m, first record, record count, leaf count, bytes, sha256.
#   OUT/src/K26FData/M%04d.lean, OUT/src/K26FData/Top.lean: the data modules (bt_bin% loader) and the table.
# Untrusted generator: the data only decide which certificate is checked.
import array, hashlib, os, struct, sys
from multiprocessing import Pool

P, OUT, JOBS = sys.argv[1], sys.argv[2], int(sys.argv[3])
N = os.path.getsize(P + ".keys") // 8
assert os.path.getsize(P + ".chosen") == 12 * N and os.path.getsize(P + ".v") == 8 * N
R, L, W = 1 << 20, 64, 26
NM = (N + R - 1) // R
NONE32, NONEK = 0xFFFFFFFF, (1 << 30) - 1

def pack(m):
    lo = m * R
    cnt = min(N, lo + R) - lo
    K = array.array("Q"); C = array.array("I"); V = array.array("d")
    with open(P + ".keys", "rb") as f: f.seek(8 * lo); K.frombytes(f.read(8 * cnt))
    with open(P + ".chosen", "rb") as f: f.seek(12 * lo); C.frombytes(f.read(12 * cnt))
    with open(P + ".v", "rb") as f: f.seek(8 * lo); V.frombytes(f.read(8 * cnt))
    nleaf = (cnt + L - 1) // L
    out = bytearray(nleaf * L * W)
    s60 = 2.0 ** 60
    for j in range(cnt):
        k = K[j]; n = k >> 58; T = k & ((1 << 58) - 1)
        c0 = C[3 * j]; c1 = C[3 * j + 1]; c2 = C[3 * j + 2]
        if c0 == NONE32: c0 = NONEK
        if c1 == NONE32: c1 = NONEK
        if c2 == NONE32: c2 = NONEK
        v = V[j]
        if not (n < 64 and T < (1 << 44) and c0 <= NONEK and c1 <= NONEK and c2 <= NONEK and 0.0 <= v <= 1.0):
            raise SystemExit("bad record %d" % (lo + j))
        x = n | (T << 6) | (c0 << 50) | (c1 << 80) | (c2 << 110) | (int(v * s60) << 140)
        out[W * j:W * j + W] = x.to_bytes(W, "little")
    fn = os.path.join(OUT, "data", "m%04d.bin" % m)
    with open(fn, "wb") as f: f.write(out)
    return (m, lo, cnt, nleaf, len(out), hashlib.sha256(out).hexdigest())

if __name__ == "__main__":
    os.makedirs(os.path.join(OUT, "data"), exist_ok=True)
    os.makedirs(os.path.join(OUT, "src", "K26FData"), exist_ok=True)
    with Pool(JOBS) as pool:
        rows = sorted(pool.map(pack, range(NM)))
    with open(os.path.join(OUT, "data", "MANIFEST.tsv"), "w") as f:
        for r in rows: f.write("%d\t%d\t%d\t%d\t%d\t%s\n" % r)
    for (m, lo, cnt, nleaf, nb, sha) in rows:
        open(os.path.join(OUT, "src", "K26FData", "M%04d.lean" % m), "w").write(
            "import Saw38aK.LitBin\n\n/-! K26F data module %d: records %d..%d (generated by tools/mkdata_k26f.py; "
            "data/m%04d.bin sha256 %s). -/\n\nnamespace K26FData\n\nopen Saw38aK\n\n"
            "set_option maxHeartbeats 0 in\nnoncomputable def M%04d : BT Nat := bt_bin%% \"../data/m%04d.bin\" %d %d\n\n"
            "end K26FData\n"
            % (m, lo, lo + cnt - 1, m, sha, m, m, nleaf, L * W))
    names = " ".join("K26FData.M%04d" % m for m in range(NM))
    imports = "\n".join("import K26FData.M%04d" % m for m in range(NM))
    open(os.path.join(OUT, "src", "K26FData", "Top.lean"), "w").write(
        imports + "\n\n/-! The K26F record table (generated): %d records in %d modules of 2^20 records, leaves of 64 "
        "records. -/\n\nnamespace K26FData\n\nopen Saw38aK\n\nnoncomputable def top : BT (BT Nat) := bt_of%% %s\n\n"
        "/-- Record `i` of the k26f certificate. -/\nnoncomputable def rd (i : Nat) : Saw38aCore.Rec := rdT top 64 16384 i\n\n"
        "/-- The number of states. -/\ndef NT : Nat := %d\n\nend K26FData\n" % (N, NM, names, N))
    print("N", N, "modules", NM)
