# gen_k26f.py SRC MODE ...: K26F module generator (untrusted; every statement it writes is checked by Lean).
#   gen_k26f.py SRC shard K [B G]    -> SRC/K26FS/D%03d/S%05d.lean: states [K B, min(NT, (K+1) B)), G per theorem
#   gen_k26f.py SRC parts [B P]      -> SRC/K26FP/P%03d.lean (P shards each) and SRC/K26F/Root.lean
#   gen_k26f.py SRC final            -> SRC/K26F/Final.lean, SRC/K26F/StatementCheck.lean
# Defaults: B = 20000 states per shard, G = 100 states per theorem, P = 256 shards per part.
import os, sys

NT = 960470402
NUM, DEN = 2725816588621027200, 1024176292618053632
SRC, MODE = sys.argv[1], sys.argv[2]

def chk(lo, k):
    return "checkRangeB2 rd NT %d %d %d %d = true" % (NUM, DEN, lo, k)

def shard_name(k):
    return "K26FS.D%03d.S%05d" % (k // 1000, k)

def tree(bnd, names):
    """A balanced term of checkRangeB2_append' combining names[j] : range [bnd[j], bnd[j+1]) into [bnd[0], bnd[-1])."""
    def go(i, j):
        if j - i == 1:
            return names[i]
        m = (i + j) // 2
        return "(checkRangeB2_append' (lo := %d) (a := %d) (b := %d) %s %s)" % (
            bnd[i], bnd[m] - bnd[i], bnd[j] - bnd[m], go(i, m), go(m, j))
    return go(0, len(names))

def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(text)

def gen_shard(k, B, G):
    lo, hi = k * B, min(NT, (k + 1) * B)
    assert lo < hi
    L = ["import Saw38aK.RangeB", "import K26FData.Top", "",
         "/-! K26F shard %d: states %d..%d (generated by tools/gen_k26f.py). -/" % (k, lo, hi - 1), "",
         "namespace %s" % shard_name(k), "", "open Saw38aK K26FData", "",
         "set_option Elab.async false", ""]
    starts = list(range(lo, hi, G))
    for j, a in enumerate(starts):
        L.append("theorem t%d : %s := by decide +kernel" % (j, chk(a, min(G, hi - a))))
    bnd = starts + [hi]
    L.append("theorem shard : %s :=\n  %s" % (chk(lo, hi - lo), tree(bnd, ["t%d" % j for j in range(len(starts))])))
    L += ["", "end %s" % shard_name(k), ""]
    write(os.path.join(SRC, "K26FS", "D%03d" % (k // 1000), "S%05d.lean" % k), "\n".join(L))

def gen_parts(B, P):
    M = (NT + B - 1) // B
    nparts = (M + P - 1) // P
    for p in range(nparts):
        ks = list(range(p * P, min(M, (p + 1) * P)))
        lo = ks[0] * B
        L = ["import %s" % shard_name(k) for k in ks] + ["",
             "/-! K26F part %d: shards %d..%d (generated). -/" % (p, ks[0], ks[-1]), "",
             "namespace K26FP.P%03d" % p, "", "open Saw38aK K26FData", ""]
        bnd = [k * B for k in ks] + [min(NT, (ks[-1] + 1) * B)]
        L.append("theorem part : %s :=\n  %s" % (chk(lo, bnd[-1] - lo), tree(bnd, ["%s.shard" % shard_name(k) for k in ks])))
        L += ["", "end K26FP.P%03d" % p, ""]
        write(os.path.join(SRC, "K26FP", "P%03d.lean" % p), "\n".join(L))
    L = ["import K26FP.P%03d" % p for p in range(nparts)] + ["",
         "/-! K26F root: all %d states (generated). -/" % NT, "", "namespace K26F.Root", "",
         "open Saw38aK K26FData", ""]
    bnd = [p * P * B for p in range(nparts)] + [NT]
    L.append("theorem all : checkRangeB2 rd NT %d %d 0 NT = true :=\n  %s" % (
        NUM, DEN, tree(bnd, ["K26FP.P%03d.part" % p for p in range(nparts)])))
    L += ["", "end K26F.Root", ""]
    write(os.path.join(SRC, "K26F", "Root.lean"), "\n".join(L))
    print("shards", M, "parts", nparts)

if MODE == "shard":
    k = int(sys.argv[3])
    B = int(sys.argv[4]) if len(sys.argv) > 4 else 20000
    G = int(sys.argv[5]) if len(sys.argv) > 5 else 100
    gen_shard(k, B, G)
elif MODE == "parts":
    B = int(sys.argv[3]) if len(sys.argv) > 3 else 20000
    P = int(sys.argv[4]) if len(sys.argv) > 4 else 256
    gen_parts(B, P)
else:
    raise SystemExit("mode?")
