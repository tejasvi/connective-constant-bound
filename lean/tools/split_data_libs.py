#!/usr/bin/env python3
"""split_data_libs.py ROOT PARTS: split the precompiled data library into PARTS libraries of consecutive chunks,
so that no shared library holds the whole certificate. Lake links into a library's shared object every module in
its roots' import closure and loads a precompiled library as a whole, so:
- L38DataP<k> (precompiled, -mcmodel=medium) has root module L38DataP<k>.lean, which imports only its own chunks;
- L38Data.All (the array of all chunks) moves into the non-precompiled L38Shard library, so no shared library links
  all chunks; the shards load the L38DataP<k> libraries as plugins and evaluate `chunks` from their native strings.
Rewrites ROOT/lakefile.toml (the original is kept as lakefile.kit.toml) and writes ROOT/L38DataP<k>.lean."""
import os, re, sys
R, PARTS = sys.argv[1], int(sys.argv[2])
NCH = 11497
lf = os.path.join(R, "lakefile.toml")
s = open(lf).read()
if not os.path.exists(os.path.join(R, "lakefile.kit.toml")):
    open(os.path.join(R, "lakefile.kit.toml"), "w").write(s)
old_data = ('# The certificate data (generated by tools/gen_data30e.sh), compiled to native code.\n[[lean_lib]]\nname = "L38Data"\n'
            'globs = ["L38Data", "L38Data.+"]\nprecompileModules = true\n')
assert s.count(old_data) == 1, "unexpected lakefile"
old_shard = '# The native_decide shard theorems (generated by tools/gen_shards30e.py).\n[[lean_lib]]\nname = "L38Shard"\nglobs = ["L38Shard.+"]\n'
assert s.count(old_shard) == 1, "unexpected lakefile (L38Shard)"
m = re.search(r'precompileModules = true\n(# about 796 GB of string data:[^\n]*\n)moreLeancArgs = \["-mcmodel=medium"\]\n', s)
assert m, "unexpected lakefile (moreLeancArgs)"
s = s.replace(old_data + m.group(1) + 'moreLeancArgs = ["-mcmodel=medium"]\n', "")
per = -(-NCH // PARTS)
libs = []
for k in range(PARTS):
    lo, hi = k * per, min(NCH, (k + 1) * per)
    mods = ["L38Data.Chunk%05d" % c for c in range(lo, hi)]
    open(os.path.join(R, "L38DataP%d.lean" % k), "w").write("".join("import %s\n" % x for x in mods))
    libs.append('# Certificate data, chunks %d..%d (generated by tools/gen_data30e.sh), compiled to native code.\n'
                '[[lean_lib]]\nname = "L38DataP%d"\nroots = ["L38DataP%d"]\nglobs = [%s]\nprecompileModules = true\n'
                'moreLeancArgs = ["-mcmodel=medium"]\n\n' % (lo, hi - 1, k, k, ", ".join('"%s"' % x for x in ["L38DataP%d" % k] + mods)))
new_shard = ('# The native_decide shard theorems (generated by tools/gen_shards30e.py), and L38Data.All (not precompiled, so\n'
             '# that no shared library links all chunks; see the data libraries above).\n'
             '[[lean_lib]]\nname = "L38Shard"\nglobs = ["L38Shard.+", "L38Data.All"]\n')
s = s.replace(old_shard, "".join(libs) + new_shard)
open(lf, "w").write(s)
print("parts", PARTS, "chunks per part", per)
