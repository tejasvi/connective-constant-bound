# gen_params30e_v1.py MANIFEST SRC: K30EData.Params (module; public exposed NT, NUM, DEN, S0).
# NT = records in MANIFEST; NUM/DEN = the v5 (N release) bound 105432502045487/39656386815908; S0 = 0, the index of the
# start key 16 << 58 (record 0 of the export; the kernel checks the start state through start_ok).
import os, sys

man, src = sys.argv[1], sys.argv[2]
rows = [l.rstrip("\n").split("\t") for l in open(man) if l.strip()]
NT = int(rows[-1][1]) + int(rows[-1][2])
assert NT == sum(int(r[2]) for r in rows)
os.makedirs(os.path.join(src, "K30EData"), exist_ok=True)
open(os.path.join(src, "K30EData", "Params.lean"), "w").write(
    "module\n\n/-! K30E parameters (generated by tools/gen_params30e_v1.py). -/\n\n@[expose] public section\n\n"
    "namespace K30EData\n\n/-- The number of states of the k30e certificate. -/\ndef NT : Nat := %d\n\n"
    "/-- The bound NUM / DEN of P20 v5 (< 2.6586513). -/\ndef NUM : Nat := 105432502045487\n\ndef DEN : Nat := 39656386815908\n\n"
    "/-- The index of the start state (key 16 << 58). -/\ndef S0 : Nat := 0\n\nend K30EData\n\nend\n" % NT)
print("NT", NT)
