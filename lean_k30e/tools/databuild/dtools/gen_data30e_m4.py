# gen_data30e_m4.py MANIFEST SRC [--top]: the K30E data modules in Lean's module-system form (untrusted generator;
# the data only decide which certificate is checked). As gen_data30e_v1.py, but each file is a `module` with the
# loader imported publicly and the definition public with its body HIDDEN: importers see
# only `M%05d : BT Nat`; a unit reads the records through `import all K30EData.M%05d`, so parts and the root never map
# the bodies. `noncomputable`, so that no code is generated for the literal. MANIFEST rows (tab separated): m, first record, record count, leaf
# count, bytes, sha256 of data/m%05d.bin. Writes SRC/K30EData/M%05d.lean per row (bt_bin% of ../data/m%05d.bin, read
# relative to the build's working directory SRC) and, with --top, SRC/K30EData/Top.lean (the two-level table of all
# modules, body exposed (constant names only), `noncomputable`). m4 replaces m3 (exposed bodies, stopped unfinished).
import os, sys

man, src = sys.argv[1], sys.argv[2]
top = "--top" in sys.argv[3:]
rows = [l.rstrip("\n").split("\t") for l in open(man) if l.strip()]
os.makedirs(os.path.join(src, "K30EData"), exist_ok=True)
for m, first, cnt, nleaf, nb, sha in rows:
    m, first, cnt, nleaf, nb = int(m), int(first), int(cnt), int(nleaf), int(nb)
    assert nb == nleaf * 1792 and nleaf == (cnt + 63) // 64 and first == m << 20 and len(sha) == 64
    open(os.path.join(src, "K30EData", "M%05d.lean" % m), "w").write(
        "module\n\npublic import Saw38aK.LitBin\n\n/-! K30E data module %d: records %d..%d (generated by "
        "tools/gen_data30e_m4.py; data/m%05d.bin sha256 %s). -/\n\npublic section\n\nnamespace K30EData\n\n"
        "open Saw38aK\n\nset_option maxHeartbeats 0 in\nnoncomputable def M%05d : BT Nat := bt_bin%% \"../data/m%05d.bin\" "
        "%d 1792\n\nend K30EData\n\nend\n" % (m, first, first + cnt - 1, m, sha, m, m, nleaf))
if top:
    ms = [int(r[0]) for r in rows]
    assert ms == list(range(len(ms)))
    NT = int(rows[-1][1]) + int(rows[-1][2])
    open(os.path.join(src, "K30EData", "Top.lean"), "w").write(
        "module\n\n" + "\n".join("public import K30EData.M%05d" % m for m in ms) +
        "\n\n/-! The K30E record table (generated by tools/gen_data30e_m4.py): %d records in %d modules of 2^20 records, "
        "leaves of 64 records. -/\n\npublic section\n\nnamespace K30EData\n\nopen Saw38aK\n\n"
        "@[expose] noncomputable def top : BT (BT Nat) := bt_of%% %s\n\nend K30EData\n\nend\n"
        % (NT, len(ms), " ".join("K30EData.M%05d" % m for m in ms)))
print("modules", len(rows), "top" if top else "")
