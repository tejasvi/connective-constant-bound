# gen_asm.py MODE ...: unit / part / root generators for the module-system K30E assembly (untrusted; every statement is
# checked by Lean). Demo on a small certificate uses the same code paths as K30E.
#   unit  NAME P PARAMSMOD MS LO HINTS G OUT [noc] -> OUT: module unit NAME; MS = "k:Const:Module,..." (shard module list);
#                                             noc: no per-group CoveredL theorems (the cov tree's leaves are the
#                                             coveredL_of_range terms themselves: half the declarations, less RSS);
#                                             P = namespace of NT/NUM/DEN, PARAMSMOD = the module defining them;
#                                             HINTS = rows "i|h|[d0]|[d1]|[d2]" for i = LO.. (consecutive)
#   part  NAME P TOPMOD PARAMSMOD UNITLIST OUT -> OUT: module part (units imported privately; public `part : CoveredG`);
#                                             UNITLIST rows "UnitName lo count k1,k2,..."
#                                             (module numbers of the unit's ms, in order); PARAMS = Lean namespace of NT/NUM/DEN
#   root  NAME P TOPMOD PARAMSMOD S0MOD PARTLIST K NUM DEN BOUND OUT -> OUT: module final (v5-shaped public theorems in
#                                             Saw38a.NAME); S0MOD = the data module holding the start record (import all)
import sys
mode = sys.argv[1]
def tree(bnd, names, lemma):
    def go(i, j):
        if j - i == 1:
            return names[i]
        m = (i + j) // 2
        return "(%s (lo := %d) (a := %d) (b := %d) %s %s)" % (lemma, bnd[i], bnd[m] - bnd[i], bnd[j] - bnd[m], go(i, m), go(m, j))
    return go(0, len(names))
if mode == "unit":
    name, P, pmod, msarg, lo, hf, G, out = sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5], int(sys.argv[6]), sys.argv[7], int(sys.argv[8]), sys.argv[9]
    noc = len(sys.argv) > 10 and sys.argv[10] == "noc"
    ms = [(int(x.split(":")[0]), x.split(":")[1], x.split(":")[2]) for x in msarg.split(",")]
    rows = [l.strip().split("|") for l in open(hf) if "|" in l]
    assert [int(r[0]) for r in rows] == list(range(lo, lo + len(rows)))
    dmods = sorted({md for _, _, md in ms})
    L = ["module", "", "public import K30B.Local"] + ["public import %s" % m for m in sorted(set(dmods) | {pmod})] + [
         "import all %s" % m for m in dmods] + [
         "", "/-! Shard unit %s: states %d..%d (generated by gen_asm.py); only `ms` and `cov` are public. -/" % (name, lo, lo + len(rows) - 1), "",
         "namespace %s" % name, "", "open Saw38aCore Saw38aK K30B", "", "set_option Elab.async false", "set_option maxRecDepth 100000", "",
         "@[expose] public noncomputable def ms : List (Nat × BT Nat) := [%s]" % ", ".join("(%d, %s)" % (k, c) for k, c, _ in ms), ""]
    bnd = list(range(lo, lo + len(rows), G)) + [lo + len(rows)]
    names = []
    for j in range(len(bnd) - 1):
        a, b = bnd[j], bnd[j + 1]
        hl = "[%s]" % ", ".join("(%s, %s, %s, %s)" % (r[1], r[2], r[3], r[4]) for r in rows[a - lo:b - lo])
        L.append("theorem g%d : checkRangeL ms %s.NT %s.NUM %s.DEN %d %s = true := by decide +kernel" % (j, P, P, P, a, hl))
        if noc:
            names.append("(coveredL_of_range ms _ _ _ _ %d g%d : CoveredL ms %s.NT %s.NUM %s.DEN %d %d)" % (a, j, P, P, P, a, b - a))
        else:
            L.append("theorem c%d : CoveredL ms %s.NT %s.NUM %s.DEN %d %d := coveredL_of_range ms _ _ _ _ %d g%d" % (j, P, P, P, a, b - a, a, j))
            names.append("c%d" % j)
    L += ["", "public theorem cov : CoveredL ms %s.NT %s.NUM %s.DEN %d %d :=" % (P, P, P, lo, len(rows)),
          "  " + tree(bnd, names, "coveredL_append"), "", "end %s" % name, ""]
    open(out, "w").write("\n".join(L))
    print("unit", name, "states", len(rows), "groups", len(names))
elif mode == "part":
    name, P, topmod, pmod, ul, out = sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5], sys.argv[6], sys.argv[7]
    units = [l.split() for l in open(ul) if l.strip()]
    L = ["module", "", "public import K30B.LocalProofs", "public import %s" % topmod, "public import %s" % pmod] + ["import %s" % u[0] for u in units] + [
         "", "/-! Part %s: %d units, imported privately; only `part` is public (generated by gen_asm.py). -/" % (name, len(units)), "",
         "namespace %s" % name, "", "open Saw38aCore Saw38aK K30B", "", "set_option maxRecDepth 100000", ""]
    bnd, names = [], []
    for j, (u, lo, cnt, ks) in enumerate(units):
        lo, cnt = int(lo), int(cnt)
        mk = "(modsOKG_nil _)"
        for k in reversed([int(x) for x in ks.split(",")]):
            mk = "(modsOKG_cons rfl %s)" % mk
        L.append("theorem u%d : CoveredG (rdT30 %s.top 64 16384) %s.NT %s.NUM %s.DEN %d %d :=" % (j, P, P, P, P, lo, cnt))
        L.append("  coveredG_of_coveredL (%s : ModsOKG %s.top %s.ms) %s.cov" % (mk, P, u, u))
        if j == 0:
            bnd.append(lo)
        assert bnd[-1] == lo, "units must be consecutive"
        bnd.append(lo + cnt)
        names.append("u%d" % j)
    L += ["", "public theorem part : CoveredG (rdT30 %s.top 64 16384) %s.NT %s.NUM %s.DEN %d %d :=" % (P, P, P, P, bnd[0], bnd[-1] - bnd[0]),
          "  " + tree(bnd, names, "coveredG_append"), "", "end %s" % name, ""]
    open(out, "w").write("\n".join(L))
    print("part", name, "units", len(units), "range", bnd[0], bnd[-1])
elif mode == "root":
    name, P, topmod, pmod, s0mod, pl, K, NUM, DEN, BOUND, out = (sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5], sys.argv[6],
        sys.argv[7], int(sys.argv[8]), int(sys.argv[9]), int(sys.argv[10]), sys.argv[11], sys.argv[12])
    parts = [l.split() for l in open(pl) if l.strip()]
    L = ["module", "", "public import Saw38a.Count", "public import Saw38a.Mu", "public import Saw38a.Bridge", "public import Saw38a.HW",
         "public import K30BP.Unit", "public import %s" % topmod, "public import %s" % pmod] + [
         "public import %s" % p[0] for p in parts] + ["import all %s" % s0mod] + [
         "", "/-! Root: all parts -> valid_of_check3c -> the v5-shaped final theorems (generated by gen_asm.py). -/", "",
         "public section", "", "namespace Saw38a", "", "open Saw38aCore Saw38aK K30B K30BP Filter Topology", "",
         "/-- Theorem 4.1 and Lemma 5.1 together (as in v5's Final.lean). -/",
         "theorem bridge_bound_of_cert' (c : Cert) {K num den : ℕ} (hc : c.Valid K) (hr : c.RatioLE num den)",
         "    (hden : 0 < den) : ∃ C : ℝ, ∀ n : ℕ, (bridgeCount n : ℝ) ≤ C * ((num : ℝ) / den) ^ n :=",
         "  ⟨c.V c.start, fun n => (Nat.cast_le.2 (bridgeCount_le_autCount' c hc n)).trans (autCount_le' c hc hr hden n)⟩", "",
         "namespace %s" % name, ""]
    bnd, names = [], []
    for j, (p, lo, cnt) in enumerate(parts):
        lo, cnt = int(lo), int(cnt)
        if j == 0:
            bnd.append(lo)
        assert bnd[-1] == lo
        bnd.append(lo + cnt)
        names.append("%s.part" % p)
    assert bnd[0] == 0
    L += ["theorem covG : CoveredG (rdT30 %s.top 64 16384) %s.NT %s.NUM %s.DEN 0 %s.NT :=" % (P, P, P, P, P),
          "  " + tree(bnd, names, "coveredG_append"), "",
          "/-- `CoveredG` and `K30BP.Covered` have the same body. -/",
          "theorem cov : Covered (rdT30 %s.top 64 16384) %s.NT %s.NUM %s.DEN 0 %s.NT := covG" % (P, P, P, P, P), "",
          "theorem start_ok : decode (rdT30 %s.top 64 16384 %s.S0).n (rdT30 %s.top 64 16384 %s.S0).T = some (startPath %d) := by" % (P, P, P, P, K),
          "  decide +kernel", "", "theorem hS0 : %s.S0 < %s.NT := by decide" % (P, P), "",
          "/-- The certificate of order %d. -/" % K,
          "theorem cert_exists : ∃ c : Cert, c.Valid %d ∧ c.RatioLE %d %d :=" % (K, NUM, DEN),
          "  ⟨certOf30 (rdT30 %s.top 64 16384) %s.NT %s.S0 hS0, valid_of_check3c hS0 (hall_of_covered cov) start_ok⟩" % (P, P, P), "",
          "/-- Unconditional: `b_n ≤ C λ^n` for the paper's `λ`. -/",
          "theorem bridge_bound : ∃ C : ℝ, ∀ n : ℕ,", "    (bridgeCount n : ℝ) ≤ C * ((%d : ℝ) / %d) ^ n := by" % (NUM, DEN),
          "  obtain ⟨c, hc, hr⟩ := cert_exists", "  simpa using bridge_bound_of_cert' c hc hr (by norm_num)", "",
          "/-- Main theorem under `HW`. -/", "theorem connective_constant_le (hHW : HW) :",
          "    ∃ μ : ℝ, Tendsto (fun n : ℕ => (sawCount n : ℝ) ^ ((1 : ℝ) / n)) atTop (𝓝 μ) ∧",
          "      μ ≤ (%d : ℝ) / %d ∧ μ < %s := by" % (NUM, DEN, BOUND),
          "  obtain ⟨μ, hμ, hle⟩ := connective_constant_le_of_bridge_bound hHW (by positivity) bridge_bound",
          "  exact ⟨μ, hμ, hle, lt_of_le_of_lt hle (by norm_num)⟩", "",
          "/-- Main theorem (no hypothesis). -/", "theorem connective_constant_le_unconditional :",
          "    ∃ μ : ℝ, Tendsto (fun n : ℕ => (sawCount n : ℝ) ^ ((1 : ℝ) / n)) atTop (𝓝 μ) ∧",
          "      μ ≤ (%d : ℝ) / %d ∧ μ < %s :=" % (NUM, DEN, BOUND), "  connective_constant_le hw'", "",
          "end %s" % name, "", "end Saw38a", "", "end", ""]
    open(out, "w").write("\n".join(L))
    print("root", name, "parts", len(parts))
